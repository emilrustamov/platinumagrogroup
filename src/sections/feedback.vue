<script setup>
import { ref, computed, onMounted, onUnmounted, onBeforeUnmount } from 'vue'
import { useI18n } from 'vue-i18n'

const { t, tm } = useI18n()

const currentIndex = ref(0)
let autoScrollTimer = null
const isVisible = ref(false)
const sectionRef = ref(null)
let observer = null

// tm() достаёт "сырой" массив объектов из locale-файла (testimonials.items)
const testimonials = computed(() => tm('testimonials.items'))

// Функция переключения на следующий слайд
const nextSlide = () => {
    if (currentIndex.value < testimonials.value.length - 1) {
        currentIndex.value++
    } else {
        currentIndex.value = 0
    }
}

// Запуск автоматической прокрутки
const startAutoScroll = () => {
    autoScrollTimer = setInterval(nextSlide, 5000)
}

const stopAutoScroll = () => {
    if (autoScrollTimer) {
        clearInterval(autoScrollTimer)
    }
}

const setSlideManually = (index) => {
    currentIndex.value = index
    stopAutoScroll()
    startAutoScroll()
}

onMounted(() => {
    observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                isVisible.value = true
                if (observer && sectionRef.value) {
                    observer.unobserve(sectionRef.value)
                }
            }
        })
    }, {
        threshold: 0.15,
        rootMargin: '0px 0px -50px 0px'
    })

    if (sectionRef.value) {
        observer.observe(sectionRef.value)
    }

    startAutoScroll()
})

onBeforeUnmount(() => {
    stopAutoScroll()
    if (observer) {
        observer.disconnect()
    }
})
</script>

